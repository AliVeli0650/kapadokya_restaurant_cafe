-- ============================================
-- HELPER FUNCTIONS
-- ============================================

-- Belirli bir tarih aralığındaki toplam geliri hesaplama
CREATE OR REPLACE FUNCTION get_total_income(start_date DATE, end_date DATE)
RETURNS NUMERIC AS $$
  SELECT COALESCE(SUM(toplam), 0)
  FROM daily_income
  WHERE date BETWEEN start_date AND end_date;
$$ LANGUAGE SQL;

-- Belirli bir tarih aralığındaki toplam gideri hesaplama
CREATE OR REPLACE FUNCTION get_total_expense(start_date DATE, end_date DATE)
RETURNS NUMERIC AS $$
  SELECT COALESCE(SUM(amount), 0)
  FROM expenses
  WHERE expense_date BETWEEN start_date AND end_date;
$$ LANGUAGE SQL;

-- Belirli bir tarih aralığındaki kar/zarar hesaplama
CREATE OR REPLACE FUNCTION get_profit_loss(start_date DATE, end_date DATE)
RETURNS NUMERIC AS $$
  SELECT get_total_income(start_date, end_date) - get_total_expense(start_date, end_date);
$$ LANGUAGE SQL;
