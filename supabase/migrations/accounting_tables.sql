-- 4. Giderler Tablosu (Expenses)
CREATE TABLE expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES expense_categories(id) ON DELETE SET NULL,
  amount NUMERIC(12,2) NOT NULL,
  description TEXT,
  expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
  invoice_number TEXT,
  vendor TEXT,
  payment_method TEXT, -- Nakit, Havale, Kredi Kartı
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Günlük Kasa Özeti (Daily Ledger)
CREATE TABLE daily_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date DATE NOT NULL UNIQUE,
  opening_balance NUMERIC(12,2) NOT NULL DEFAULT 0,
  total_income NUMERIC(12,2) DEFAULT 0,
  total_expense NUMERIC(12,2) DEFAULT 0,
  closing_balance NUMERIC(12,2) GENERATED ALWAYS AS (opening_balance + total_income - total_expense) STORED,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

